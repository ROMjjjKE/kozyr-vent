import puppeteer from 'puppeteer-core';
const URL = process.env.SITE || 'https://romjjjke.github.io/kozyr-vent/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const p = await b.newPage();
await p.setViewport({ width: 1440, height: 900 });
await p.goto(URL, { waitUntil: 'networkidle2' });
await p.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
await p.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 1000));
const jump = async (sel, offset = 0) => {
  await p.evaluate((s, o) => { const el = document.querySelector(s); window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - o, behavior: 'instant' }); }, sel, offset);
  await new Promise(r => setTimeout(r, 1100));
};
await p.screenshot({ path: 'screenshots/desktop-1440.png' });
const stage = await p.evaluate(() => Math.round(document.querySelector('.line__stage').getBoundingClientRect().top + window.scrollY));
await p.evaluate(y => window.scrollTo({ top: y, behavior: 'instant' }), stage + 1000);
await new Promise(r => setTimeout(r, 1200));
await p.screenshot({ path: 'screenshots/desktop-etapy.png' });
await jump('#sklad', 90);
await p.screenshot({ path: 'screenshots/desktop-sklad.png' });
await jump('.band', -140);
console.log('band nw', await p.evaluate(() => document.querySelector('.band__img').naturalWidth), 'y', await p.evaluate(() => Math.round(window.scrollY)));
await p.screenshot({ path: 'screenshots/desktop-obekt.png' });
await jump('#zayavka', 60);
await p.screenshot({ path: 'screenshots/desktop-zayavka.png' });
await p.close();

const m = await b.newPage();
await m.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await m.goto(URL, { waitUntil: 'networkidle2' });
await m.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
await m.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 1000));
await m.screenshot({ path: 'screenshots/mobile-390.png' });
await m.evaluate(() => { const el = document.querySelector('#etapy'); window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY + 120, behavior: 'instant' }); });
await new Promise(r => setTimeout(r, 900));
await m.screenshot({ path: 'screenshots/mobile-390-etapy.png' });
await m.evaluate(() => { const el = document.querySelector('#zayavka'); window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY, behavior: 'instant' }); });
await new Promise(r => setTimeout(r, 900));
await m.screenshot({ path: 'screenshots/mobile-390-zayavka.png' });
await m.close();
await b.close();
